CREATE TABLE projects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    description VARCHAR(2000),
    -- No ON DELETE: a user who still owns projects can't be deleted by accident.
    owner_id    BIGINT        NOT NULL REFERENCES users (id),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_projects_owner_id ON projects (owner_id);

-- Join table between users and projects. Its own columns (joined_at) are why it isn't a plain @ManyToMany.
CREATE TABLE project_members (
    project_id BIGINT      NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    joined_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- One row per (project, user): nobody can be added to the same project twice.
    PRIMARY KEY (project_id, user_id)
);

-- The primary key already covers lookups by project_id. "Which projects is this user in?" needs its own index.
CREATE INDEX idx_project_members_user_id ON project_members (user_id);
