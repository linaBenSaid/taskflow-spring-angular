CREATE TABLE tasks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Deleting a project deletes its tasks.
    project_id  BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    title       VARCHAR(200)  NOT NULL,
    description VARCHAR(5000),
    status      VARCHAR(20)   NOT NULL DEFAULT 'TODO',
    priority    VARCHAR(20)   NOT NULL DEFAULT 'MEDIUM',
    due_date    DATE,
    -- Optional. If the user is deleted, the task stays and becomes unassigned.
    assignee_id BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT tasks_status_check   CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    CONSTRAINT tasks_priority_check CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH'))
);

-- The Kanban board and the filters always ask "tasks of project X (with status Y)".
-- One index on (project_id, status) serves both: it also works for project_id alone.
CREATE INDEX idx_tasks_project_id_status ON tasks (project_id, status);

-- "Tasks assigned to user X" (assignee filter, "my tasks").
CREATE INDEX idx_tasks_assignee_id ON tasks (assignee_id);
