CREATE TABLE comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Deleting a task deletes its comments.
    task_id    BIGINT        NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    -- Optional. If the author's account is deleted, the comment stays so the conversation still makes sense.
    author_id  BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    body       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Comments are always read per task, oldest first: this index finds them already in that order.
CREATE INDEX idx_comments_task_id_created_at ON comments (task_id, created_at);
